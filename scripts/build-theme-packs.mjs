import path from "node:path";
import {
  getThemeDirs,
  loadTheme,
  resolveTheme,
  semanticColorKeys,
  validateTheme,
  writeText
} from "./theme-io.mjs";

const themeDirs = await getThemeDirs();

if (themeDirs.length === 0) {
  throw new Error("No theme packs found in themes/.");
}

const registry = {};
const combinedCss = ["/* Generated by scripts/build-theme-packs.mjs. Do not edit by hand. */"];

for (const themeName of themeDirs) {
  const theme = await loadTheme(themeName);
  validateTheme(theme);
  const resolved = resolveTheme(theme);
  registry[themeName] = resolved;

  await writeText(path.join(theme.dir, "generated", "theme.resolved.json"), `${JSON.stringify(resolved, null, 2)}\n`);
  const themeCss = renderThemeCss(themeName, resolved);
  await writeText(path.join(theme.dir, "generated", "theme.css"), themeCss);
  combinedCss.push(themeCss.trim());
  await writeText(path.join(theme.dir, "generated", "theme.native.ts"), renderNativeTheme(resolved));
}

await writeText("packages/theme/src/generated.ts", renderThemeRegistry(registry));
await writeText("packages/theme/src/themes.css", `${combinedCss.join("\n\n")}\n`);

console.log(`Built ${themeDirs.length} theme packs.`);

function renderThemeCss(themeName, resolved) {
  const blocks = [];

  for (const modeName of ["light", "dark"]) {
    const colors = resolved.modes[modeName].colors;
    const lines = semanticColorKeys.map((key) => `  --dc-color-${toKebab(key)}: ${colors[key]};`);
    blocks.push(
      `:root[data-dc-theme="${themeName}"][data-dc-mode="${modeName}"],\n[data-dc-theme="${themeName}"][data-dc-mode="${modeName}"] {\n${lines.join("\n")}\n}`
    );
  }

  return `${blocks.join("\n\n")}\n`;
}

function renderNativeTheme(resolved) {
  return `// Generated by scripts/build-theme-packs.mjs. Do not edit by hand.
export const theme = ${JSON.stringify(resolved, null, 2)} as const;

export type Theme = typeof theme;
`;
}

function renderThemeRegistry(registry) {
  return `// Generated by scripts/build-theme-packs.mjs. Do not edit by hand.
export const designcThemes = ${JSON.stringify(registry, null, 2)} as const;

export const themeNames = Object.keys(designcThemes) as Array<keyof typeof designcThemes>;

export type DesignCThemeRegistry = typeof designcThemes;
export type DesignCThemeName = keyof DesignCThemeRegistry;
export type DesignCThemeMode = "light" | "dark";
`;
}

function toKebab(value) {
  return value.replace(/[A-Z]/g, (match) => `-${match.toLowerCase()}`);
}
