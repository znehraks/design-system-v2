import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokenDir = path.join(repoRoot, "packages/foundation/tokens");
const outputFile = path.join(repoRoot, "packages/foundation/src/generated.ts");

const files = (await readdir(tokenDir)).filter((file) => file.endsWith(".json")).sort();
const merged = {};

for (const file of files) {
  const tokenJson = JSON.parse(await readFile(path.join(tokenDir, file), "utf8"));
  for (const [key, value] of Object.entries(tokenJson)) {
    if (key !== "$schema") {
      merged[key] = value;
    }
  }
}

const cssVariables = {};
collectCssVariables(merged, ["dc"]);

function collectCssVariables(node, pathParts) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("$")) {
      continue;
    }

    if (value && typeof value === "object" && "$value" in value) {
      cssVariables[`--${[...pathParts, key].join("-")}`] = value.$value;
    } else if (value && typeof value === "object") {
      collectCssVariables(value, [...pathParts, key]);
    }
  }
}

const contents = `// Generated by scripts/build-foundation.mjs. Do not edit by hand.
export const foundationTokens = ${JSON.stringify(merged, null, 2)} as const;

export const foundationCssVariables = ${JSON.stringify(cssVariables, null, 2)} as const;

export type FoundationTokens = typeof foundationTokens;
export type FoundationCssVariables = typeof foundationCssVariables;
`;

await writeFile(outputFile, contents);
console.log(`Built ${outputFile}.`);
